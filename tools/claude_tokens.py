#!/usr/bin/env python3
"""Token accounting for Claude Code sessions building this repository.

Reads local Claude Code transcripts under ~/.claude/projects/<slug>/*.jsonl
and outputs per-request, per-session, per-tool, and per-file token and USD
list-price aggregates.

Usage:
    python3 tools/claude_tokens.py
    python3 tools/claude_tokens.py --days 3
    python3 tools/claude_tokens.py --out data/claude-tokens/last3d.json
    python3 tools/claude_tokens.py --project-glob '*my-repo*'
"""

from __future__ import annotations

import argparse
import base64
import binascii
import json
import os
import re
import sys
from collections import defaultdict
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# List price per 1M tokens: (input_usd, output_usd).
PRICES: dict[str, tuple[float, float]] = {
    "claude-fable-5": (10.0, 50.0),
    "claude-fable-5-2": (10.0, 50.0),
    "claude-mythos-5": (10.0, 50.0),
    "claude-opus-5": (5.0, 25.0),
    "claude-opus-5-5": (5.0, 25.0),
    "claude-opus-4-8": (5.0, 25.0),
    "claude-opus-4-7": (5.0, 25.0),
    "claude-opus-4-6": (5.0, 25.0),
    "claude-sonnet-5": (2.0, 10.0),
    "claude-sonnet-5-5": (3.0, 15.0),
    "claude-sonnet-4-6": (3.0, 15.0),
    "claude-haiku-5-5": (1.0, 5.0),
    "claude-haiku-4-5": (1.0, 5.0),
}
FAST_PRICES: dict[str, tuple[float, float]] = {
    "claude-opus-5": (10.0, 50.0),
    "claude-opus-5-5": (10.0, 50.0),
    "claude-opus-4-8": (10.0, 50.0),
}
ALIASES: dict[str, str] = {
    "opus": "claude-opus-5-5",
    "sonnet": "claude-sonnet-5-5",
    "haiku": "claude-haiku-5-5",
    "fable": "claude-fable-5-2",
}
CACHE_READ_FACTOR = 0.1
CACHE_WRITE_5M_FACTOR = 1.25
CACHE_WRITE_1H_FACTOR = 2.0
CHARS_PER_TOKEN = 4.0
IMAGE_PIXELS_PER_TOKEN = 750
MAX_IMAGE_EDGE = 1568
FALLBACK_IMAGE_TOKENS = 1600

_REMINDER = re.compile(r"<system-reminder>.*?</system-reminder>", re.S)
_TAG = re.compile(r"<[^>]{1,40}>")
_ANSI = re.compile(r"\x1b?\[[0-9;]{1,8}m")
_CMD_NAME = re.compile(r"<command-name>\s*/?([\w:-]+)", re.I)
_CMD_ARGS = re.compile(r"<command-args>(.*?)</command-args>", re.S | re.I)

_SKIP_LABELS = (
    "Caveat: The messages below were generated by the user",
    "This session is being continued from a previous conversation",
    "Please continue the conversation from where we left it off",
)
_META_COMMANDS = {
    "clear", "model", "compact", "config", "resume", "cost", "status", "exit",
    "help", "fast", "login", "logout", "doctor", "memory", "terminal-setup",
    "vim", "theme", "ide", "mcp", "bug", "release-notes", "privacy-settings",
    "upgrade", "permissions", "hooks", "agents", "output-style", "statusline",
    "export", "add-dir", "todos", "context", "usage", "artifacts", "workflows",
}


def canonical_model(model: str | None) -> str | None:
    if not model or model == "<synthetic>":
        return None
    return ALIASES.get(model, model)


def resolve_rates(model: str, speed: str | None) -> tuple[float, float] | None:
    table = FAST_PRICES if speed == "fast" and model in FAST_PRICES else PRICES
    if model in table:
        return table[model]
    # Longest prefix first, so claude-sonnet-5-5-<date> never matches claude-sonnet-5.
    for prefix in sorted(table, key=len, reverse=True):
        if model.startswith(prefix):
            return table[prefix]
    return None


UNPRICED: set[str] = set()


def request_cost(model: str | None, usage: dict, speed: str | None) -> float:
    canon = canonical_model(model)
    if canon is None:
        return 0.0
    rates = resolve_rates(canon, speed)
    if rates is None:
        UNPRICED.add(canon)
        return 0.0
    inp, outp = rates
    creation = usage.get("cache_creation") or {}
    tok_1h = creation.get("ephemeral_1h_input_tokens", 0)
    tok_5m = creation.get("ephemeral_5m_input_tokens", 0)
    if not creation:
        tok_5m = usage.get("cache_creation_input_tokens", 0)
    billed_in = (
        usage.get("input_tokens", 0)
        + tok_5m * CACHE_WRITE_5M_FACTOR
        + tok_1h * CACHE_WRITE_1H_FACTOR
        + usage.get("cache_read_input_tokens", 0) * CACHE_READ_FACTOR
    )
    return billed_in / 1e6 * inp + usage.get("output_tokens", 0) / 1e6 * outp


def _png_size(data: bytes) -> tuple[int, int] | None:
    if len(data) < 24 or data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR":
        return None
    return (int.from_bytes(data[16:20], "big"), int.from_bytes(data[20:24], "big"))


def _jpeg_size(data: bytes) -> tuple[int, int] | None:
    if len(data) < 4 or data[:2] != b"\xff\xd8":
        return None
    i = 2
    while i + 9 < len(data):
        if data[i] != 0xFF:
            i += 1
            continue
        marker = data[i + 1]
        if marker == 0xFF:
            i += 1
            continue
        if marker in (0x01, 0xD8, 0xD9) or 0xD0 <= marker <= 0xD7:
            i += 2
            continue
        seg_len = int.from_bytes(data[i + 2 : i + 4], "big")
        if seg_len < 2:
            return None
        if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
            height = int.from_bytes(data[i + 5 : i + 7], "big")
            width = int.from_bytes(data[i + 7 : i + 9], "big")
            return (width, height)
        i += 2 + seg_len
    return None


def image_tokens(source: dict) -> int:
    b64 = source.get("data") or ""
    if not b64:
        return 0
    head = b64[:1024]
    head = head[: len(head) - len(head) % 4]
    try:
        raw = base64.b64decode(head, validate=False)
    except (binascii.Error, ValueError):
        return FALLBACK_IMAGE_TOKENS
    size = _png_size(raw) or _jpeg_size(raw)
    if not size:
        return FALLBACK_IMAGE_TOKENS
    width, height = size
    if width <= 0 or height <= 0:
        return FALLBACK_IMAGE_TOKENS
    longest = max(width, height)
    if longest > MAX_IMAGE_EDGE:
        scale = MAX_IMAGE_EDGE / longest
        width = max(1, int(width * scale))
        height = max(1, int(height * scale))
    return max(1, round(width * height / IMAGE_PIXELS_PER_TOKEN))


def block_chars(content: object) -> int:
    if content is None:
        return 0
    if isinstance(content, str):
        return len(content)
    if isinstance(content, list):
        total = 0
        for part in content:
            if isinstance(part, dict):
                if part.get("type") == "text":
                    total += len(part.get("text") or "")
                elif part.get("type") == "image":
                    total += int(image_tokens(part.get("source") or {}) * CHARS_PER_TOKEN)
                else:
                    total += len(json.dumps(part, ensure_ascii=False))
            else:
                total += len(str(part))
        return total
    return len(json.dumps(content, ensure_ascii=False))


def clean_prompt(text: str) -> str:
    text = _REMINDER.sub("", text)
    text = _TAG.sub("", text)
    text = _ANSI.sub("", text)
    return " ".join(text.split())


def usable_label(raw: str | None) -> str | None:
    raw = raw or ""
    if "<local-command-stdout>" in raw:
        return None
    match = _CMD_NAME.search(raw)
    if match:
        name = match.group(1).lower()
        if name in _META_COMMANDS:
            return None
        args = _CMD_ARGS.search(raw)
        arg = clean_prompt(args.group(1)) if args else ""
        return f"/{name} {arg}".strip()[:200]
    text = clean_prompt(raw)
    if not text or any(text.startswith(p) for p in _SKIP_LABELS):
        return None
    return text[:200]


def read_agent_type(path: Path) -> str:
    meta_path = path.with_suffix(".meta.json")
    try:
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return "workflow" if "workflows" in path.parts else "subagent"
    return meta.get("agentType") or meta.get("subagent_type") or "subagent"


def tool_target(name: str, tool_input: object) -> str | None:
    if not isinstance(tool_input, dict):
        return None
    for key in ("file_path", "notebook_path", "path", "pattern", "url"):
        value = tool_input.get(key)
        if isinstance(value, str) and value:
            return value[:200]
    if name == "Bash":
        cmd = tool_input.get("command")
        if isinstance(cmd, str):
            return " ".join(cmd.split())[:120]
    if name in ("Agent", "Task"):
        return tool_input.get("subagent_type") or tool_input.get("description")
    return None


class Accumulator:
    def __init__(self) -> None:
        self.requests = 0
        self.input = 0
        self.cache_write = 0
        self.cache_read = 0
        self.output = 0
        self.thinking = 0
        self.cost = 0.0

    def add(self, usage: dict, cost: float) -> None:
        self.requests += 1
        self.input += usage.get("input_tokens", 0)
        self.cache_write += usage.get("cache_creation_input_tokens", 0)
        self.cache_read += usage.get("cache_read_input_tokens", 0)
        self.output += usage.get("output_tokens", 0)
        details = usage.get("output_tokens_details") or {}
        self.thinking += details.get("thinking_tokens", 0)
        self.cost += cost

    @property
    def total_in(self) -> int:
        return self.input + self.cache_write + self.cache_read

    def as_dict(self) -> dict:
        return {
            "requests": self.requests,
            "input_tokens": self.input,
            "cache_write_tokens": self.cache_write,
            "cache_read_tokens": self.cache_read,
            "output_tokens": self.output,
            "thinking_tokens": self.thinking,
            "total_input_tokens": self.total_in,
            "total_tokens": self.total_in + self.output,
            "cost_usd": round(self.cost, 4),
        }


def parse_ts(raw: str | None) -> datetime | None:
    if not raw:
        return None
    try:
        return datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except ValueError:
        return None


def analyse(project_dirs: list[Path], since: datetime | None) -> dict:
    seen_requests: set[str] = set()
    overall = Accumulator()
    by_model: dict[str, Accumulator] = defaultdict(Accumulator)
    by_day: dict[str, Accumulator] = defaultdict(Accumulator)
    by_session: dict[str, Accumulator] = defaultdict(Accumulator)
    by_effort: dict[str, Accumulator] = defaultdict(Accumulator)
    main_chain = Accumulator()
    side_chain = Accumulator()
    by_agent_type: dict[str, Accumulator] = defaultdict(Accumulator)
    subagent_cost_by_session: dict[str, float] = defaultdict(float)

    session_meta: dict[str, dict] = {}
    top_requests: list[dict] = []
    pending: dict[str, tuple[str, str | None, str]] = {}
    tool_stats: dict[str, dict[str, int]] = defaultdict(
        lambda: {"calls": 0, "result_chars": 0, "input_chars": 0, "max_chars": 0}
    )
    target_stats: dict[tuple[str, str], dict[str, int]] = defaultdict(
        lambda: {"calls": 0, "result_chars": 0}
    )
    session_tool_chars: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))

    files_scanned = 0
    lines_scanned = 0

    for project in project_dirs:
        for path in sorted(project.rglob("*.jsonl")):
            files_scanned += 1
            parts = path.relative_to(project).parts
            if len(parts) == 1:
                owner_session = path.stem
                agent_type = None
            else:
                owner_session = parts[0]
                agent_type = read_agent_type(path)
            with path.open("r", encoding="utf-8", errors="replace") as handle:
                for line in handle:
                    line = line.strip()
                    if not line:
                        continue
                    lines_scanned += 1
                    try:
                        rec = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    if not isinstance(rec, dict):
                        continue

                    kind = rec.get("type")
                    session = owner_session
                    ts = parse_ts(rec.get("timestamp"))
                    if since and ts and ts < since:
                        continue

                    message = rec.get("message")
                    if not isinstance(message, dict):
                        message = {}
                    content = message.get("content")

                    meta = session_meta.setdefault(
                        session,
                        {
                            "session_id": session,
                            "project": project.name,
                            "label": None,
                            "first_seen": None,
                            "last_seen": None,
                            "branch": rec.get("gitBranch"),
                            "kind": rec.get("sessionKind"),
                        },
                    )
                    if ts:
                        iso = ts.isoformat()
                        if meta["first_seen"] is None or iso < meta["first_seen"]:
                            meta["first_seen"] = iso
                        if meta["last_seen"] is None or iso > meta["last_seen"]:
                            meta["last_seen"] = iso

                    if kind == "user":
                        want_label = meta["label"] is None and agent_type is None
                        if isinstance(content, str) and want_label:
                            meta["label"] = usable_label(content)
                        elif isinstance(content, list):
                            for block in content:
                                if not isinstance(block, dict):
                                    continue
                                if block.get("type") == "text" and want_label:
                                    label = usable_label(block.get("text"))
                                    if label:
                                        meta["label"] = label
                                        want_label = False
                                elif block.get("type") == "tool_result":
                                    use_id = block.get("tool_use_id")
                                    chars = block_chars(block.get("content"))
                                    name, target, owner = pending.pop(
                                        use_id, ("unknown", None, session)
                                    )
                                    stat = tool_stats[name]
                                    stat["result_chars"] += chars
                                    stat["max_chars"] = max(stat["max_chars"], chars)
                                    session_tool_chars[owner][name] += chars
                                    if target:
                                        tstat = target_stats[(name, target)]
                                        tstat["calls"] += 1
                                        tstat["result_chars"] += chars
                        continue

                    if kind != "assistant":
                        continue

                    usage = message.get("usage")
                    model = message.get("model")
                    if isinstance(content, list):
                        for block in content:
                            if isinstance(block, dict) and block.get("type") == "tool_use":
                                name = block.get("name") or "unknown"
                                tool_input = block.get("input") or {}
                                target = tool_target(name, tool_input)
                                pending[block.get("id")] = (name, target, session)
                                stat = tool_stats[name]
                                stat["calls"] += 1
                                stat["input_chars"] += len(
                                    json.dumps(tool_input, ensure_ascii=False)
                                )

                    if not isinstance(usage, dict):
                        continue
                    request_id = rec.get("requestId") or rec.get("uuid")
                    if not request_id or request_id in seen_requests:
                        continue
                    seen_requests.add(request_id)

                    canon = canonical_model(model)
                    if canon is None:
                        continue
                    cost = request_cost(model, usage, usage.get("speed"))

                    overall.add(usage, cost)
                    by_model[canon].add(usage, cost)
                    by_session[session].add(usage, cost)
                    by_effort[rec.get("effort") or "unset"].add(usage, cost)
                    if ts:
                        by_day[ts.date().isoformat()].add(usage, cost)
                    if agent_type is not None or rec.get("isSidechain"):
                        side_chain.add(usage, cost)
                        by_agent_type[agent_type or "inline"].add(usage, cost)
                        subagent_cost_by_session[session] += cost
                    else:
                        main_chain.add(usage, cost)

                    top_requests.append(
                        {
                            "request_id": request_id,
                            "session_id": session,
                            "timestamp": rec.get("timestamp"),
                            "model": canon,
                            "effort": rec.get("effort"),
                            "sidechain": bool(rec.get("isSidechain")),
                            "input_tokens": usage.get("input_tokens", 0),
                            "cache_write_tokens": usage.get("cache_creation_input_tokens", 0),
                            "cache_read_tokens": usage.get("cache_read_input_tokens", 0),
                            "output_tokens": usage.get("output_tokens", 0),
                            "thinking_tokens": (
                                usage.get("output_tokens_details") or {}
                            ).get("thinking_tokens", 0),
                            "cost_usd": round(cost, 4),
                        }
                    )

    top_requests.sort(key=lambda r: r["cost_usd"], reverse=True)
    sessions = []
    for session, acc in by_session.items():
        meta = session_meta.get(session, {})
        tools = sorted(
            session_tool_chars.get(session, {}).items(),
            key=lambda kv: kv[1],
            reverse=True,
        )[:5]
        row = {
            "session_id": session,
            "project": meta.get("project"),
            "label": meta.get("label"),
            "branch": meta.get("branch"),
            "first_seen": meta.get("first_seen"),
            "last_seen": meta.get("last_seen"),
            "top_tools": [
                {"tool": name, "est_tokens": int(chars / CHARS_PER_TOKEN)}
                for name, chars in tools
            ],
            "subagent_cost_usd": round(subagent_cost_by_session.get(session, 0.0), 4),
        }
        row.update(acc.as_dict())
        sessions.append(row)
    sessions.sort(key=lambda s: s["cost_usd"], reverse=True)

    tools_out = [
        {
            "tool": name,
            "calls": stat["calls"],
            "result_est_tokens": int(stat["result_chars"] / CHARS_PER_TOKEN),
            "call_est_tokens": int(stat["input_chars"] / CHARS_PER_TOKEN),
            "avg_result_est_tokens": (
                int(stat["result_chars"] / CHARS_PER_TOKEN / stat["calls"])
                if stat["calls"]
                else 0
            ),
            "max_result_est_tokens": int(stat["max_chars"] / CHARS_PER_TOKEN),
        }
        for name, stat in tool_stats.items()
    ]
    tools_out.sort(key=lambda t: t["result_est_tokens"], reverse=True)

    targets_out = [
        {
            "tool": name,
            "target": target,
            "calls": stat["calls"],
            "result_est_tokens": int(stat["result_chars"] / CHARS_PER_TOKEN),
        }
        for (name, target), stat in target_stats.items()
    ]
    targets_out.sort(key=lambda t: t["result_est_tokens"], reverse=True)

    return {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "scanned": {
            "projects": [p.name for p in project_dirs],
            "files": files_scanned,
            "lines": lines_scanned,
            "requests": overall.requests,
            "since": since.isoformat() if since else None,
        },
        "totals": overall.as_dict(),
        "by_model": {k: v.as_dict() for k, v in sorted(by_model.items())},
        "by_effort": {k: v.as_dict() for k, v in sorted(by_effort.items())},
        "by_day": {k: v.as_dict() for k, v in sorted(by_day.items())},
        "chain": {"main": main_chain.as_dict(), "subagent": side_chain.as_dict()},
        "by_agent_type": {
            k: v.as_dict()
            for k, v in sorted(by_agent_type.items(), key=lambda kv: kv[1].cost, reverse=True)
        },
        "sessions": sessions,
        "tools": tools_out,
        "targets": targets_out[:150],
        "top_requests": top_requests[:100],
    }


def fmt(n: int) -> str:
    return f"{n:,}"


def print_summary(report: dict, limit: int) -> None:
    t = report["totals"]
    s = report["scanned"]
    print(
        f"Scanned {s['files']} transcript files, {fmt(s['lines'])} lines, "
        f"{fmt(s['requests'])} billed requests."
    )
    print(
        f"Total tokens {fmt(t['total_tokens'])}  "
        f"(in {fmt(t['total_input_tokens'])}, out {fmt(t['output_tokens'])}, "
        f"thinking {fmt(t['thinking_tokens'])})"
    )
    print(f"  cache read  {fmt(t['cache_read_tokens'])}")
    print(f"  cache write {fmt(t['cache_write_tokens'])}")
    print(f"  fresh input {fmt(t['input_tokens'])}")
    print(f"Estimated list cost  USD {t['cost_usd']:,.2f}\n")
    print("By model")
    for model, acc in report["by_model"].items():
        print(
            f"  {model:<20} {acc['requests']:>6} req  "
            f"{fmt(acc['total_tokens']):>15} tok  USD {acc['cost_usd']:>10,.2f}"
        )
    print("\nMain chain vs subagents")
    for key, acc in report["chain"].items():
        print(
            f"  {key:<10} {acc['requests']:>6} req  "
            f"{fmt(acc['total_tokens']):>15} tok  USD {acc['cost_usd']:>10,.2f}"
        )
    print(f"\nTop {limit} sessions by cost")
    for row in report["sessions"][:limit]:
        label = (row["label"] or "(no prompt captured)")[:70]
        print(
            f"  USD {row['cost_usd']:>9,.2f}  {fmt(row['total_tokens']):>14} tok  "
            f"{row['requests']:>4} req  {(row['first_seen'] or '')[:10]}  {label}"
        )


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, OSError):
        pass
    default_glob = f"*{ROOT.name}*"
    parser = argparse.ArgumentParser(description="Claude Code token report")
    parser.add_argument("--days", type=int, default=None, help="only count requests newer than N days")
    parser.add_argument("--out", type=Path, default=None, help="write full JSON report to this path")
    parser.add_argument("--project-glob", default=default_glob, help="~/.claude/projects glob")
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(os.path.expanduser("~")) / ".claude" / "projects",
    )
    parser.add_argument("--limit", type=int, default=15, help="rows per table in stdout summary")
    args = parser.parse_args()

    project_dirs = sorted(p for p in args.root.glob(args.project_glob) if p.is_dir())
    if not project_dirs:
        print(f"No project directories match {args.project_glob} under {args.root}", file=sys.stderr)
        return 1

    since = datetime.now(timezone.utc) - timedelta(days=args.days) if args.days else None
    report = analyse(project_dirs, since)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(report, indent=1, ensure_ascii=False), encoding="utf-8")
        print(f"Wrote {args.out}", file=sys.stderr)
    print_summary(report, args.limit)
    if UNPRICED:
        print(
            f"\nWARNING: no list price for {', '.join(sorted(UNPRICED))}; counted as USD 0. "
            "Add them to PRICES.",
            file=sys.stderr,
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
